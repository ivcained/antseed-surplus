import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile,mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import plugin from '@local/antseed-provider-surplus';
import {captureUnitBillingContext,computeFinalUnitBilling} from '@antseed/buyer-core';
import {buildSellerPluginRuntimeEnv} from '../node_modules/@antseed/cli/dist/cli/commands/seller/start.js';
import {createGateway} from '../lib/gateway.mjs';
import {buildAntseedConfig,buildProtocolMap} from '../lib/runtime.mjs';

test('real local plugin, CLI config, authenticated gateway and image adapter agree on paid output-unit billing',async t=>{
 const stateDir=await mkdtemp(join(tmpdir(),'content-pipeline-'));t.after(()=>rm(stateDir,{recursive:true,force:true}));
 const image=await readFile(new URL('./fixtures/red.png',import.meta.url));
 const entry={model:'venice-sd35',kind:'image',provider:'venice',inputs:['text'],parameters:{n:1,size:'1024x1024'},estimatedCostUsd:.02,pricingBasis:'operator-estimate'};
 const expiresAt=new Date(Date.now()+60000).toISOString(),zero={inputUsdPerMillion:0,outputUsdPerMillion:0,cachedInputUsdPerMillion:0};
 const quote={kind:'image',upstreamModel:entry.model,provider:'api.venice.ai',media:entry,pricing:zero,upstreamPricing:zero,maxPricePer1m:0,unitPriceUsd:.03,estimatedUpstreamUsd:.022,policyExpiresAt:expiresAt};
 const quotes={generatedAt:new Date().toISOString(),services:{[entry.model]:quote}};
 const settings={stateDir,surplusBaseUrl:'https://api.surplusintelligence.ai/v1',models:['text'],mediaConfig:{services:[entry],expiresAt},gatewayPort:18791,maxTokens:64,maxInputBytes:4096,maxConcurrent:1,quoteMaxAgeMs:60000,mediaMaxInputBytes:1048576};
 const calls=[];
 const gateway=createGateway({settings,apiKey:'inf_fixture_upstream_only',localToken:'local-gateway-token',getQuotes:()=>quotes,fetchImpl:async(url,init)=>{calls.push({url,init});return Response.json({created:1,data:[{b64_json:image.toString('base64')}]});}});
 await new Promise(resolve=>gateway.listen(0,resolve));t.after(()=>{gateway.closeAllConnections();gateway.close();});
 settings.gatewayPort=gateway.address().port;
 const cfg=buildAntseedConfig(settings,quotes);
 const env=buildSellerPluginRuntimeEnv(cfg.seller,'surplus');
 const provider=plugin.createProvider({...env,OPENAI_API_KEY:'local-gateway-token',SURPLUS_PROTOCOLS_JSON:JSON.stringify(buildProtocolMap(quotes))});
 const req={requestId:'offline-pipeline-image',method:'POST',path:'/v1/images/generations',headers:{'content-type':'application/json','x-antseed-service':entry.model,authorization:'Bearer untrusted_caller_token'},body:Buffer.from(JSON.stringify({model:entry.model,prompt:'A simple red square',n:1,size:'1024x1024',response_format:'b64_json',provider:'untrusted'}))};
 const response=await provider.handleRequest(req);
 assert.equal(response.statusCode,200);
 assert.equal(JSON.parse(Buffer.from(response.body).toString()).data[0].b64_json,image.toString('base64'));
 assert.equal(calls.length,1);assert.equal(calls[0].url,'https://api.surplusintelligence.ai/v1/images/generations');
 assert.equal(calls[0].init.headers.authorization,'Bearer inf_fixture_upstream_only');
 assert.equal(JSON.parse(calls[0].init.body).provider,'api.venice.ai');
 assert.doesNotMatch(JSON.stringify(response),/inf_fixture|untrusted_caller_token|local-gateway-token/);
 const captured=captureUnitBillingContext({sellerPeerId:'a'.repeat(40),provider:'surplus',service:entry.model,serviceApiProtocol:'openai-images',request:req});
 const tariff=cfg.seller.providers.surplus.services[entry.model].unitBillingModels['openai-images'];
 const bill=computeFinalUnitBilling(tariff,captured.context,response,captured.requestFacts);
 assert.equal(bill.costUsdc,30000n);assert.equal(bill.usage.units.output_images,1);
});
